CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS citext;

CREATE ROLE chegai_app LOGIN PASSWORD 'chegai_app' NOSUPERUSER NOBYPASSRLS;
GRANT CONNECT ON DATABASE chegai TO chegai_app;
GRANT USAGE ON SCHEMA public TO chegai_app;

ALTER DEFAULT PRIVILEGES FOR ROLE chegai IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO chegai_app;
ALTER DEFAULT PRIVILEGES FOR ROLE chegai IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO chegai_app;
ALTER DEFAULT PRIVILEGES FOR ROLE chegai IN SCHEMA public
  GRANT EXECUTE ON FUNCTIONS TO chegai_app;
